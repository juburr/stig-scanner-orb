"""Generate the compact CircleCI entry point for the readable checklist script.

CircleCI starts run commands via bash -c, subject to Linux's 128 KiB single
argument limit. Decode the exact source into a shell variable and execute it
with bash's eval builtin, which does not put the source in an execve argument.
The payload is repository code, never caller data. Python stdlib is already
required by the generator. No runtime download or persistent code file is used.
"""
import argparse
import base64
import hashlib
from pathlib import Path
import re
import textwrap
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/scripts/checklist.sh'
ENTRY = ROOT / 'src/scripts/checklist-packed.sh'
LIMIT = 120000  # Headroom below Linux MAX_ARG_STRLEN (131072).


def render(source):
    payload = '\n'.join(textwrap.wrap(base64.b64encode(zlib.compress(source, 9)).decode('ascii'), 100))
    digest = hashlib.sha256(source).hexdigest()
    return '''#!/usr/bin/env bash
# Generated by tools/pack-checklist.py; edit checklist.sh and regenerate.
# Keep CircleCI's bash -c argument below Linux MAX_ARG_STRLEN.
set -euo pipefail
STIG_CHECKLIST_SCRIPT="$(python3 - <<'PY_CHECKLIST_PACKED'
import base64
import hashlib
import sys
import zlib
payload = """
''' + payload + '''
"""
source = zlib.decompress(base64.b64decode("".join(payload.split()), validate=True))
if hashlib.sha256(source).hexdigest() != "''' + digest + '''":
    raise ValueError("packed checklist source hash mismatch")
sys.stdout.write(source.decode("utf-8"))
PY_CHECKLIST_PACKED
)"
# eval is a shell builtin; the decoded source never becomes an OS argument.
# The hash-bound payload is the reviewed repository script, not user input.
eval "${STIG_CHECKLIST_SCRIPT}"
'''


def verify(source, entry):
    # Verify source equality rather than zlib byte equality across toolchains.
    match = re.search(r'payload = """\n(.*?)\n"""', entry, re.S)
    if not match:
        raise ValueError('packed checklist has no payload')
    decoded = zlib.decompress(base64.b64decode(''.join(match.group(1).split()), validate=True))
    if decoded != source or entry != render_from_payload(source, match.group(1)):
        raise ValueError('packed checklist differs from checklist.sh; run python3 tools/pack-checklist.py')
    if len(entry.encode()) >= LIMIT:
        raise ValueError('packed checklist exceeds the 120000-byte command budget')


def render_from_payload(source, payload):
    # Preserve only an equivalent compressed payload; every executable wrapper
    # byte must still match the canonical template, including its source hash.
    template = render(source)
    return re.sub(r'(?<=payload = """\n).*?(?=\n""")', lambda _: payload, template, count=1, flags=re.S)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = SOURCE.read_bytes()
    if not args.check:
        ENTRY.write_text(render(source), encoding='utf-8')
    verify(source, ENTRY.read_text(encoding='utf-8'))
    print('packed checklist source/hash and command-size budget verified')


if __name__ == '__main__':
    main()
