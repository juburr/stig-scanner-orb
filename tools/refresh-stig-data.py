"""Rebuild deterministic, offline DISA bundles for every pinned datastream.

python3 tools/refresh-stig-data.py --source-dir /path/to/approved/zips
python3 tools/refresh-stig-data.py --source-dir /tmp/stig-zips --download
python3 tools/refresh-stig-data.py --source-dir /path/to/zips --check

Network access is explicit and maintainer-only. Source ZIP checksums live in
stig-sources.json; a changed download is never accepted automatically. All
sources are validated before any generated file is changed. --check regenerates
in memory and fails if committed scripts or the generator's bundle pins drift.
"""

import argparse
import base64
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import textwrap
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "src/scripts/checklist.sh"
MARKER_BEGIN = "# BEGIN GENERATED BUNDLE_TABLE (tools/refresh-stig-data.py)"
MARKER_END = "# END GENERATED BUNDLE_TABLE"
POLICY = "https://www.cyber.mil/privacy-security"


def generator():
    code = SCRIPT.read_text().split("<<'PY_CHECKLIST'\n", 1)[1].split("\nPY_CHECKLIST\n", 1)[0]
    scope = {"__name__": "refresh"}
    exec(compile(code, str(SCRIPT), "exec"), scope)
    return scope


def render_script(alias, encoded):
    # Only a short path is exported. The payload is a script include, never an
    # environment value: CircleCI's environment-size limit does not apply.
    name = "STIG_DATA_" + alias.upper()
    return """#!/usr/bin/env bash
# Generated by tools/refresh-stig-data.py; do not edit the payload.
# DISA reference content. Attribution and reuse terms: THIRD_PARTY_NOTICES.md.
# Stage privately, without following a reused output path or touching rootfs.
# A staging error is reported by checklist generation; summarize owns the gate.
set -uo pipefail
export NAME=""
if [ -n "${BASH_ENV:-}" ]; then
    printf 'export NAME=\\n' >> "${BASH_ENV}" || exit 0
fi
if [ "${PARAM_CHECKLIST:-auto}" = "none" ]; then
    exit 0
fi
bundle_path="$(mktemp "${TMPDIR:-/tmp}/stig-data-ALIAS.XXXXXXXX")" || exit 0
if cat > "${bundle_path}" <<'STIG_DATA_B64'
PAYLOAD
STIG_DATA_B64
then
    export NAME="${bundle_path}"
    if [ -n "${BASH_ENV:-}" ]; then
        printf 'export NAME=%q\\n' "${bundle_path}" >> "${BASH_ENV}" || exit 0
    fi
else
    rm -f -- "${bundle_path}"
fi
exit 0
""".replace("NAME", name).replace("ALIAS", alias).replace("PAYLOAD", "\n".join(textwrap.wrap(encoded, 76)))


def build(source_dir, download=False):
    gen = generator()
    sources = json.loads((ROOT / "tools/stig-sources.json").read_text())
    if set(sources) != {"rhel8", "rhel9", "rhel10", "ubuntu2204"}:
        raise ValueError("source manifest must name exactly the four supported pinned products")
    scripts, descriptors = {}, {}
    for alias, source in sorted(sources.items()):
        if not re.fullmatch(r"[a-z0-9]+", alias) or Path(source["filename"]).name != source["filename"]:
            raise ValueError("invalid source name")
        if source["url"] != "https://dl.dod.cyber.mil/wp-content/uploads/stigs/zip/" + source["filename"]:
            raise ValueError("source must be the official DISA ZIP URL")
        path = source_dir / source["filename"]
        if download:
            with urllib.request.urlopen(source["url"], timeout=60) as response:
                raw = response.read(gen["MAX_DISA_BYTES"] + 1)
        else:
            raw = gen["read_capped"](path, gen["MAX_DISA_BYTES"], "DISA source ZIP")
        if len(raw) > gen["MAX_DISA_BYTES"] or hashlib.sha256(raw).hexdigest() != source["sha256"]:
            raise ValueError(f"{source['filename']}: source ZIP does not match its reviewed SHA-256")
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            members = [
                m for m in z.infolist() if not m.is_dir() and m.filename.lower().endswith("manual-xccdf.xml")
            ]
            if len(members) != 1 or members[0].file_size > gen["MAX_DISA_BYTES"]:
                raise ValueError("source ZIP needs exactly one bounded manual XCCDF")
            with z.open(members[0]) as f:
                xml = f.read(gen["MAX_DISA_BYTES"] + 1)
            if len(xml) > gen["MAX_DISA_BYTES"]:
                raise ValueError("oversized manual XCCDF")
        disa = gen["parse_disa"](io.BytesIO(xml))
        gen["validate_disa"](disa)
        if disa["completeness"] != "inventory":
            raise ValueError("a bundled release must have a verified identifier inventory")
        matches = [
            (sha, entry)
            for sha, entry in gen["RELEASE_TABLE"].items()
            if entry[4]["filename"] == "ssg-" + alias + "-ds.xml"
        ]
        if len(matches) != 1:
            raise ValueError(f"{alias}: expected exactly one pinned datastream")
        sha, entry = matches[0]
        expected_id = gen["SSG_STIG_IDS"][entry[0].replace("xccdf_org.ssgproject.content_benchmark_", "")][0]
        if disa["benchmark_id"] != expected_id or (disa["version"], disa["releaseinfo"]) != entry[3]:
            raise ValueError(f"{alias}: DISA source is not the pinned datastream release")
        disa.pop("completeness")
        disa["profiles"] = [sorted(p) for p in disa["profiles"]]
        disa["groups"].sort(key=lambda g: int(g["vid"][2:]))
        payload = {
            "schema": "stig-scanner-orb/stig-data/v1",
            "datastream_sha256": sha,
            "stig": disa,
            "source": {
                "url": source["url"],
                "sha256": source["sha256"],
                "member": members[0].filename,
                "xccdf_sha256": hashlib.sha256(xml).hexdigest(),
                "credits": source["credits"],
                "reuse_policy": POLICY,
            },
        }
        data = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()
        compressed = io.BytesIO()
        with gzip.GzipFile(fileobj=compressed, mode="wb", filename="", mtime=0, compresslevel=9) as f:
            f.write(data)
        scripts[alias] = render_script(alias, base64.b64encode(compressed.getvalue()).decode())
        descriptors[sha] = {
            "alias": alias,
            "json_sha256": hashlib.sha256(data).hexdigest(),
            "source_sha256": source["sha256"],
            "xccdf_sha256": hashlib.sha256(xml).hexdigest(),
        }
    if set(descriptors) != set(gen["RELEASE_TABLE"]):
        raise ValueError("every release-table datastream must have exactly one bundle")
    # JSON objects also form a Python literal here (all values are strings).
    table = (
        MARKER_BEGIN
        + "\nBUNDLE_TABLE = "
        + json.dumps(descriptors, sort_keys=True, indent=4)
        + "\n"
        + MARKER_END
    )
    text = SCRIPT.read_text()
    if text.count(MARKER_BEGIN) != 1 or text.count(MARKER_END) != 1:
        raise ValueError("bundle table markers must be unique")
    text = text[: text.index(MARKER_BEGIN)] + table + text[text.index(MARKER_END) + len(MARKER_END) :]
    return scripts, text


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source-dir", type=Path, required=True)
    ap.add_argument("--download", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    scripts, text = build(a.source_dir, a.download)
    outputs = {ROOT / "src/scripts/stig-data" / (alias + ".sh"): data for alias, data in scripts.items()}
    outputs[SCRIPT] = text
    if a.check:
        different = [
            str(path.relative_to(ROOT))
            for path, data in outputs.items()
            if not path.exists() or path.read_text() != data
        ]
        if different:
            raise SystemExit("generated bundles differ: " + ", ".join(different))
        print("All DISA bundles and their pins reproduce exactly")
    else:
        for path, data in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data)
        print(f"Generated {len(scripts)} DISA bundles; source ZIP checksums verified")


if __name__ == "__main__":
    main()
